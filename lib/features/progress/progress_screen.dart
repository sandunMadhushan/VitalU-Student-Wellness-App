class ProgressScreen extends StatefulWidget {
  const ProgressScreen({super.key});
  @override
  State<ProgressScreen> createState() => _ProgressScreenState();
}

class _ProgressScreenState extends State<ProgressScreen> {
  bool _habits = true;
  bool _loading = true;
  Map<String, int> _water = {};
  Map<String, int> _minutes = {};
  List<Rec> _sleep = [];
  List<Rec> _moods = [];
  List<Rec> _assessments = [];
  Map<String, DateTime> _earned = {};
  List<Rec> _badges = [];

  @override
  void initState() {
    super.initState();
    _load();
  }

  Future<void> _load() async {
    try {
      final now = DateTime.now();
      final from = dayStart(now).subtract(const Duration(days: 27));
      final r = await Future.wait([
        Repo.waterByDay(28),
        Repo.minutesByDay(from, now),
        Repo.sleepBetween(from, now),
        Repo.moodsSince(from),
        Repo.assessments(),
        Repo.earnedBadges(),
        Repo.badges(),
      ]);
      _water = r[0] as Map<String, int>;
      _minutes = r[1] as Map<String, int>;
      _sleep = r[2] as List<Rec>;
      _moods = r[3] as List<Rec>;
      _assessments = (r[4] as List<Rec>).where((a) => a['status'] == 'completed').toList();
      _earned = r[5] as Map<String, DateTime>;
      _badges = r[6] as List<Rec>;
    } catch (e) {
      debugPrint('progress: $e');
    }
    if (mounted) setState(() => _loading = false);
  }

  List<DateTime> _days(int n, {int offset = 0}) {
    final today = dayStart(DateTime.now());
    return [for (int i = n - 1 + offset; i >= offset; i--) today.subtract(Duration(days: i))];
  }

  double _avg(List<double> v) => v.isEmpty ? 0 : v.reduce((a, b) => a + b) / v.length;

  List<double> _waterSeries(List<DateTime> days) => [for (final d in days) (_water[isoDate(d)] ?? 0) / 1000.0];
  List<double> _minSeries(List<DateTime> days) => [for (final d in days) (_minutes[isoDate(d)] ?? 0).toDouble()];
  List<double> _sleepSeries(List<DateTime> days) {
    final m = {for (final s in _sleep) s['sleep_date'] as String: Repo.sleepMinutes(s) / 60.0};
    return [for (final d in days) m[isoDate(d)] ?? 0];
  }

  String? _trend(List<double> cur, List<double> prev) {
    final a = _avg(cur.where((x) => x > 0).toList()), b = _avg(prev.where((x) => x > 0).toList());
    if (a == 0 || b == 0) return null;
    final p = ((a - b) / b * 100).round();
    if (p.abs() < 3) return 'Steady';
    return p > 0 ? '+$p%' : '$p%';
  }

  Future<void> _export() async {
    final p = AppState.instance.profile;
    final last7 = _days(7);
    try {
      await sharePdf(
        title: 'Wellness Summary',
        subtitle: '${p?.fullName ?? ''} • ${pdfDate(last7.first)} – ${pdfDate(last7.last)}',
        filename: 'VitalU_Wellness_Summary_${isoDate(DateTime.now())}.pdf',
        sections: {
          'Body measurements': [
            ['Height', p?.heightCm == null ? '—' : '${p!.heightCm!.round()} cm'],
            ['Weight', p?.weightKg == null ? '—' : '${p!.weightKg} kg'],
            ['BMI', p?.bmi == null ? '—' : p!.bmi!.toStringAsFixed(1)],
            ['Waist-to-hip ratio', p?.whr == null ? '—' : p!.whr!.toStringAsFixed(2)],
          ],
          'Last 7 days': [
            ['Average water', '${_avg(_waterSeries(last7)).toStringAsFixed(1)} L/day'],
            ['Average active minutes', '${_avg(_minSeries(last7)).round()} min/day'],
            ['Average sleep (logged nights)', '${_avg(_sleepSeries(last7).where((x) => x > 0).toList()).toStringAsFixed(1)} h'],
            ['Mood check-ins', '${_moods.where((m) => DateTime.parse(m['logged_at']).isAfter(last7.first)).length}'],
          ],
          'Periodic assessments': [
            for (final a in _assessments) [a['title'] ?? 'Assessment', '${a['result_label'] ?? ''} (${pdfDate(DateTime.parse(a['completed_at']).toLocal())})'],
            if (_assessments.isEmpty) ['No completed assessments yet', ''],
          ],
          'Milestones earned': [
            for (final b in _badges.where((b) => _earned.containsKey(b['code']))) [b['title'], pdfDate(_earned[b['code']]!)],
            if (_earned.isEmpty) ['None yet — every small step counts', ''],
          ],
        },
        footer: 'Generated by VitalU for personal reflection. This summary is not a medical diagnosis.',
      );
    } catch (e) {
      if (mounted) toast(context, 'Could not create the PDF.', error: true);
    }
  }

  Future<void> _targets() async {
    final p = AppState.instance.profile;
    double water = (p?.waterGoalMl ?? 2500).toDouble(), sleep = p?.sleepGoalHours ?? 8, steps = (p?.stepGoal ?? 8000).toDouble();
    await showVSheet(context, builder: (ctx) => StatefulBuilder(builder: (ctx, set) {
          Widget row(String t, String v) => Row(children: [Expanded(child: Text(t, style: T.labelLg)), Text(v, style: T.labelLg.c(AppColors.primary))]);
          return Column(crossAxisAlignment: CrossAxisAlignment.stretch, children: [
            Text('Adjust Habit Targets', style: T.headlineMd),
            const SizedBox(height: Sp.md),
            row('Daily water', '${Fmt.litres(water)} L'),
            VSlider(value: water, min: 1500, max: 4000, divisions: 25, onChanged: (x) => set(() => water = x)),
            row('Sleep target', '${sleep.toStringAsFixed(1)} h'),
            VSlider(value: sleep, min: 6, max: 10, divisions: 8, onChanged: (x) => set(() => sleep = x)),
            row('Daily steps', Fmt.thousands(steps)),
            VSlider(value: steps, min: 3000, max: 15000, divisions: 24, onChanged: (x) => set(() => steps = x)),
            const SizedBox(height: Sp.md),
            PrimaryButton('Save Targets', onTap: () async {
              await AppState.instance.updateProfile({'water_goal_ml': water.round(), 'sleep_goal_hours': sleep, 'step_goal': steps.round()});
              if (ctx.mounted) Navigator.pop(ctx);
              _load();
            }),
          ]);
        }));
  }

  @override
  Widget build(BuildContext context) {
    return VPage(
      header: const MainHeader('Vitalu   Your Progress & Trends'),
      nav: NavTab.progress,
      onRefresh: _load,
      children: [
        Column(crossAxisAlignment: CrossAxisAlignment.stretch, children: [
          Row(children: [
            Expanded(
              child: Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
                Text('Your Progress', style: T.headlineMd),
                Text('Gentle trends & holistic balance over time', style: T.bodySm.c(AppColors.onSurfaceVariant)),
              ]),
            ),
            TagPill('Paced', icon: Symbols.eco, bg: AppColors.surfaceContainerHigh, fg: AppColors.tertiary),
          ]),
          const SizedBox(height: 16),
          Container(
            padding: const EdgeInsets.all(4),
            decoration: BoxDecoration(color: AppColors.surfaceContainer, borderRadius: BorderRadius.circular(Rad.full)),
            child: Row(children: [
              for (final t in [(true, 'Daily Habits', Symbols.spa), (false, 'Assessments', Symbols.health_and_safety)])
                Expanded(
                  child: GestureDetector(
                    onTap: () => setState(() => _habits = t.$1),
                    child: AnimatedContainer(
                      duration: const Duration(milliseconds: 200),
                      padding: const EdgeInsets.symmetric(vertical: 8),
                      decoration: BoxDecoration(
                        color: _habits == t.$1 ? AppColors.surfaceContainerLowest : Colors.transparent,
                        borderRadius: BorderRadius.circular(Rad.full),
                        boxShadow: _habits == t.$1 ? Shadows.tinted(AppColors.primary, opacity: 0.08, blur: 12, y: 4, spread: 0) : null,
                      ),
                      child: Row(mainAxisAlignment: MainAxisAlignment.center, children: [
                        Icon(t.$3, size: 18, color: _habits == t.$1 ? AppColors.primary : AppColors.onSurfaceVariant),
                        const SizedBox(width: 6),
                        Text(t.$2, style: T.labelMd.c(_habits == t.$1 ? AppColors.primary : AppColors.onSurfaceVariant)),
                      ]),
                    ),
                  ),
                ),
            ]),
          ),
        ]),
        if (_loading) const Loading() else ...(_habits ? _habitsView() : _assessmentView()),
      ],
    );
  }

  List<Widget> _habitsView() {
    final p = AppState.instance.profile;
    final cur = _days(7), prev = _days(7, offset: 7);
    final w = _waterSeries(cur), wp = _waterSeries(prev);
    final s = _sleepSeries(cur), sp = _sleepSeries(prev);
    final m = _minSeries(cur), mp = _minSeries(prev);
    final moodCounts = <String, int>{};
    for (final x in _moods.where((x) => DateTime.parse(x['logged_at']).isAfter(cur.first))) {
      moodCounts[x['mood']] = (moodCounts[x['mood']] ?? 0) + 1;
    }
    final topMood = moodCounts.isEmpty ? null : (moodCounts.entries.toList()..sort((a, b) => b.value.compareTo(a.value))).first.key;
    const moodScore = {'Joyful': 5.0, 'Centered': 4.5, 'Calm': 4.0, 'Tired': 2.5, 'Stressed': 2.0, 'Anxious': 1.5};
    final moodSeries = [
      for (final d in cur)
        _avg(_moods.where((x) => isoDate(DateTime.parse(x['logged_at']).toLocal()) == isoDate(d)).map((x) => moodScore[x['mood']] ?? 3.0).toList())
    ];
    final latestBadge = _earned.isEmpty ? null : (_earned.entries.toList()..sort((a, b) => b.value.compareTo(a.value))).first;
    final badgeRow = latestBadge == null ? null : _badges.where((b) => b['code'] == latestBadge.key).firstOrNull;

    // 4-week hydration chart
    final weeks = [for (int i = 3; i >= 0; i--) _days(7, offset: i * 7)];
    final weekAvgs = [for (final wk in weeks) _avg(_waterSeries(wk))];
    final goalL = (p?.waterGoalMl ?? 2500) / 1000;
    final all28 = _waterSeries(_days(28));
    final met = all28.where((x) => x >= goalL).length;
    final metPct = (met / 28 * 100).round();
    final best = weekAvgs.indexOf(weekAvgs.reduce((a, b) => a > b ? a : b)) + 1;

    return [
      VCard(
        gradient: LinearGradient(begin: Alignment.topLeft, end: Alignment.bottomRight, colors: [AppColors.surfaceContainerLow, AppColors.surfaceContainer, AppColors.secondaryFixed.withValues(alpha: 0.2)]),
        shadow: Shadows.card,
        onTap: () => context.push('/milestones'),
        child: Row(children: [
          Container(
            width: 120,
            height: 120,
            decoration: BoxDecoration(borderRadius: BorderRadius.circular(16), boxShadow: Shadows.tinted(AppColors.primary, opacity: 0.12, blur: 24, y: 8, spread: 0)),
            child: const AssetImg('trend_ribbon', radius: 16),
          ),
          const SizedBox(width: 16),
          Expanded(
            child: Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
              TagPill('Week ${weekOfYear(DateTime.now())} Milestone', icon: Symbols.verified, bg: AppColors.surfaceContainerLowest.withValues(alpha: 0.8), fg: AppColors.primary),
              const SizedBox(height: 8),
              Text(badgeRow != null ? '${badgeRow['title']} Earned' : 'Your Rhythm is Growing', style: T.headlineSm),
              const SizedBox(height: 4),
              Text(
                badgeRow != null
                    ? 'You unlocked this on ${DateFormat('MMM d').format(latestBadge!.value)}. Proud of your pacing! Tap to see all milestones.'
                    : 'Log water, sleep and meals to see gentle trends and unlock milestones. Tap to explore.',
                style: T.bodySm.c(AppColors.onSurfaceVariant).lh(1.6),
              ),
            ]),
          ),
        ]),
      ),
      LayoutBuilder(builder: (context, c) {
        final cw = (c.maxWidth - Sp.sm) / 2;
        return Wrap(spacing: Sp.sm, runSpacing: Sp.sm, children: [
          SizedBox(width: cw, child: _metric(Symbols.water_drop, AppColors.surfaceContainerLow, AppColors.primary, _trend(w, wp), 'Hydration', _avg(w).toStringAsFixed(1), ' L /day', w, () => context.push('/tools/water'))),
          SizedBox(
              width: cw,
              child: _metric(Symbols.bedtime, AppColors.secondaryFixed.withValues(alpha: 0.4), AppColors.secondary, _trend(s, sp) ?? 'Steady', 'Sleep Rest',
                  _avg(s.where((x) => x > 0).toList()).toStringAsFixed(1), ' hrs avg', s, () => context.push('/tools/sleep'))),
          SizedBox(width: cw, child: _metric(Symbols.directions_walk, AppColors.tertiaryFixed.withValues(alpha: 0.4), AppColors.tertiary, _trend(m, mp), 'Movement', _avg(m).round().toString(), ' mins/day', m, () => context.push('/tools/activity'))),
          SizedBox(
              width: cw,
              child: _metric(Symbols.self_improvement, AppColors.primaryFixed, AppColors.primaryContainer, topMood == null ? null : 'Calm', 'Emotional Flow', topMood ?? 'Check in', '', moodSeries,
                  () => context.push('/home'))),
        ]);
      }),
      VCard(
        shadow: Shadows.card,
        child: Column(crossAxisAlignment: CrossAxisAlignment.stretch, children: [
          Row(crossAxisAlignment: CrossAxisAlignment.start, children: [
            Expanded(
              child: Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
                Text('Hydration & Energy Rhythm', style: T.headlineSm),
                const SizedBox(height: 2),
                Text(weekAvgs.every((x) => x == 0) ? 'Start logging water to see your rhythm' : 'Peak consistency achieved during Week $best', style: T.bodySm.c(AppColors.onSurfaceVariant)),
              ]),
            ),
            TagPill('Past 4 Weeks', bg: AppColors.surfaceContainerHigh),
          ]),
          const SizedBox(height: Sp.md),
          Container(
            padding: const EdgeInsets.all(12),
            decoration: BoxDecoration(color: AppColors.surfaceContainerLow, borderRadius: BorderRadius.circular(Rad.base)),
            child: Row(children: [
              IconCircle(Symbols.verified, size: 32, iconSize: 18, bg: AppColors.primaryFixed),
              const SizedBox(width: 10),
              Expanded(
                child: Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
                  Text('$metPct% Goal Met', style: T.labelMd),
                  Text('$met of 28 days at ${goalL.toStringAsFixed(1)}L+', style: T.labelSm.c(AppColors.onSurfaceVariant)),
                ]),
              ),
              Icon(metPct >= 50 ? Symbols.check_circle : Symbols.water_drop, size: 14, color: AppColors.tertiary),
              const SizedBox(width: 2),
              Text(metPct >= 50 ? 'On Track' : 'Building', style: T.labelSm.c(AppColors.tertiary)),
            ]),
          ),
          const SizedBox(height: Sp.md),
          Stack(children: [
            Padding(padding: const EdgeInsets.only(top: 24), child: Sparkline(values: weekAvgs, color: AppColors.primary, height: 160, baseline: goalL, showDots: true)),
            Positioned(
              right: 0,
              top: 0,
              child: Pill(color: AppColors.inverseSurface, padding: const EdgeInsets.symmetric(horizontal: 10, vertical: 4), child: Text('${weekAvgs.last.toStringAsFixed(1)}L • this week', style: T.labelSm.c(AppColors.inverseOnSurface))),
            ),
            Positioned(left: 4, top: 26, child: Text('Daily Baseline (${goalL.toStringAsFixed(1)}L)', style: T.labelSm.s(9).c(AppColors.outline))),
          ]),
          const SizedBox(height: 6),
          Row(mainAxisAlignment: MainAxisAlignment.spaceBetween, children: [
            for (int i = 0; i < 4; i++)
              Text('W${i + 1} ${DateFormat('MMM dd').format(weeks[i].first)}', style: T.labelSm.c(i == 3 ? AppColors.primary : AppColors.onSurfaceVariant)),
          ]),
        ]),
      ),
      if (badgeRow != null)
        Container(
          padding: const EdgeInsets.all(Sp.md),
          decoration: BoxDecoration(color: AppColors.surfaceContainerHigh.withValues(alpha: 0.6), borderRadius: BorderRadius.circular(Rad.lg)),
          child: Row(crossAxisAlignment: CrossAxisAlignment.start, children: [
            IconCircle(iconByName(badgeRow['icon']), size: 44, iconSize: 24, bg: AppColors.secondaryFixed, fg: AppColors.secondary),
            const SizedBox(width: 14),
            Expanded(
              child: Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
                Row(children: [
                  Flexible(child: Text('${badgeRow['title']} Badge', style: T.headlineSm.s(16))),
                  const SizedBox(width: 8),
                  TagPill('Earned', bg: AppColors.surfaceContainerLowest, fg: AppColors.secondary),
                ]),
                const SizedBox(height: 4),
                Text(badgeRow['description'] ?? '', style: T.bodySm.c(AppColors.onSurfaceVariant).lh(1.6)),
              ]),
            ),
          ]),
        ),
      PrimaryButton('Export Wellness Summary (PDF)', leadingIcon: Symbols.download, color: AppColors.onSurface, fg: AppColors.surface, height: 52, onTap: _export),
      SoftButton('Adjust Habit Targets', icon: Symbols.tune, color: AppColors.surfaceContainer, height: 48, style: T.labelMd, onTap: _targets),
    ];
  }

  Widget _metric(IconData icon, Color bg, Color fg, String? chip, String label, String value, String unit, List<double> series, VoidCallback onTap) => VCard(
        shadow: Shadows.soft,
        onTap: onTap,
        child: Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
          Row(children: [
            IconCircle(icon, size: 36, iconSize: 20, bg: bg, fg: fg),
            const Spacer(),
            if (chip != null)
              TagPill(chip,
                  icon: chip.startsWith('+') ? Symbols.trending_up : (chip.startsWith('-') ? Symbols.trending_down : null),
                  bg: chip.startsWith('+') ? AppColors.tertiaryFixed : (chip == 'Calm' ? AppColors.secondaryFixed : AppColors.surfaceContainerHigh),
                  fg: chip.startsWith('+') ? AppColors.onTertiaryFixed : (chip == 'Calm' ? AppColors.onSecondaryFixed : AppColors.onSurfaceVariant)),
          ]),
          const SizedBox(height: 10),
          Text(label, style: T.labelSm.c(AppColors.onSurfaceVariant)),
          Text.rich(TextSpan(text: value, children: [TextSpan(text: unit, style: T.bodySm.c(AppColors.onSurfaceVariant))]), style: T.headlineSm, maxLines: 1, overflow: TextOverflow.ellipsis),
          const SizedBox(height: 8),
          Sparkline(values: series, color: fg),
        ]),
      );

  List<Widget> _assessmentView() {
    if (_assessments.isEmpty) {
      return [
        EmptyState(
          icon: Symbols.health_and_safety,
          title: 'No assessment history yet',
          text: 'Your periodic university health assessments will appear here so you can see changes between terms.',
          action: SoftButton('View Health Assessments', icon: Symbols.arrow_forward, expand: false, onTap: () => context.push('/assessments')),
        ),
      ];
    }
    final ordered = _assessments.reversed.toList();
    List<double> series(String k) => [for (final a in ordered) ((a['scores'] as Map?)?[k] as num?)?.toDouble() ?? 0];
    Widget chartCard(String title, String k, Color c, String unit, {bool lowerBetter = false}) {
      final s = series(k);
      final last = s.last, first = s.first;
      final diff = last - first;
      return VCard(
        shadow: Shadows.soft,
        child: Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
          Row(children: [
            Expanded(child: Text(title, style: T.labelLg)),
            Text('${last % 1 == 0 ? last.toInt() : last.toStringAsFixed(1)}$unit', style: T.headlineSm.c(c)),
          ]),
          if (s.length > 1)
            Text('${diff >= 0 ? '+' : ''}${diff.toStringAsFixed(1)} since first assessment ${((diff < 0) == lowerBetter) ? '🌿' : ''}', style: T.labelSm.c(AppColors.onSurfaceVariant)),
          const SizedBox(height: 8),
          Sparkline(values: s, color: c, height: 60, showDots: true),
        ]),
      );
    }

    return [
      chartCard('BMI', 'bmi', AppColors.primary, '', lowerBetter: true),
      chartCard('Perceived stress (PSS-4, lower is calmer)', 'stress', AppColors.secondary, '/16', lowerBetter: true),
      chartCard('Active days per week', 'activity_days', AppColors.tertiary, ' days'),
      chartCard('Nutrition habits score', 'diet_score', AppColors.butterAccent, '/10'),
      Text('Assessment History', style: T.headlineSm),
      for (final a in _assessments)
        VCard(
          shadow: Shadows.tiny,
          onTap: () => showAssessmentSummary(context, a),
          child: Row(children: [
            IconCircle(Symbols.check_circle, size: 40, iconSize: 20, bg: AppColors.surfaceContainer, fg: AppColors.tertiary, fill: 1),
            const SizedBox(width: 12),
            Expanded(
              child: Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
                Text(a['title'] ?? 'Assessment', style: T.labelLg),
                Text('${DateFormat('MMM d, yyyy').format(DateTime.parse(a['completed_at']).toLocal())} • ${a['result_label'] ?? ''}', style: T.bodySm.c(AppColors.onSurfaceVariant)),
              ]),
            ),
            Icon(Symbols.chevron_right, color: AppColors.outlineVariant),
          ]),
        ),
    ];
  }
}
