"""Builds the periodic assessment questionnaire outputs from one source.

    python -P supabase/seed/build_questionnaire.py

Reads supabase/seed/assessment_questionnaire.json and writes:
  - assets/assessment/questionnaire.json  (the app's offline copy)
  - supabase/seed/assessment_questionnaire.sql  (domains and questions seed)
  - docs/assessment-questionnaire.md  (the questionnaire as a document)
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = ROOT / 'supabase' / 'seed' / 'assessment_questionnaire.json'
data = json.loads(SRC.read_text(encoding='utf-8'))
domains, questions = data['domains'], data['questions']

# --- App copy --------------------------------------------------------------
app = ROOT / 'assets' / 'assessment' / 'questionnaire.json'
app.parent.mkdir(parents=True, exist_ok=True)
app.write_text(json.dumps(data, ensure_ascii=False, separators=(',', ':')), encoding='utf-8')


# --- SQL seed --------------------------------------------------------------
def lit(v):
    if v is None:
        return 'null'
    if isinstance(v, bool):
        return 'true' if v else 'false'
    if isinstance(v, (int, float)):
        return str(v)
    if isinstance(v, (dict, list)):
        return "'" + json.dumps(v, ensure_ascii=False).replace("'", "''") + "'::jsonb"
    return "'" + str(v).replace("'", "''") + "'"


rows = []
for i, d in enumerate(domains, 1):
    rows.append(f"  ({d['id']}, {lit(d['title'])}, {lit(d['blurb'])}, {lit(d['icon'])}, {i}, true)")
sql = ['-- Generated by supabase/seed/build_questionnaire.py. Do not edit by hand.',
       'insert into public.assessment_domains (id, title, blurb, icon, position, active) values',
       ',\n'.join(rows),
       'on conflict (id) do update set title = excluded.title, blurb = excluded.blurb, icon = excluded.icon, position = excluded.position;',
       '']
qrows = []
pos = {}
for q in questions:
    pos[q['domain']] = pos.get(q['domain'], 0) + 1
    qrows.append('  (' + ', '.join([
        lit(q['id']), str(q['domain']), str(pos[q['domain']]), lit(q['kind']), lit(q.get('style')), lit(q['text']), lit(q.get('help')),
        lit(q.get('image')), lit(q.get('options', [])), lit(q.get('unit')), lit(q.get('min')), lit(q.get('max')), lit(q.get('max_choices')),
        lit(q.get('prefill')), lit(q.get('optional', False)), lit(q.get('show_if')), 'true',
    ]) + ')')
sql += ['insert into public.assessment_questions (id, domain_id, position, kind, style, text, help, image, options, unit, min_value, max_value, max_choices, prefill, optional, show_if, active) values',
        ',\n'.join(qrows) + ';', '']
(ROOT / 'supabase' / 'seed' / 'assessment_questionnaire.sql').write_text('\n'.join(sql), encoding='utf-8')

# --- Document --------------------------------------------------------------
KIND = {'single': 'Choose one', 'multi': 'Choose all that apply', 'scale': '1 to 5 rating', 'number': 'Number', 'text': 'Free text (optional)', 'profile': 'Confirm details'}
md = ['# VitalU periodic health assessment: questionnaire', '',
      f'Version {data["version"]}. Sent every six months by the university health administration. '
      'About 7 minutes; most questions are a single tap.', '',
      '## How to read this document', '',
      '- Each section matches one area of the admin dashboard.',
      '- **Score** shows how an answer counts towards that area\'s well-being score (0 to 100). '
      'A higher score is always the healthier answer. Questions without scores are reported as counts only.',
      '- Food questions ask about **the last 7 days** and define **one serving** in household measures '
      '(one cupped hand = ½ cup, one fist = 1 cup, palm-sized piece of fish or chicken).',
      '- Section 11 (Clinical measurements) can be shown or hidden by the administration for each round.', '']
n = 0
for d in domains:
    md += [f'## Section {d["id"]}. {d["title"]}', '', f'_{d["blurb"]}_', '']
    for q in [q for q in questions if q['domain'] == d['id']]:
        n += 1
        flags = [KIND.get(q['kind'], q['kind'])]
        if q.get('max_choices'):
            flags.append(f'up to {q["max_choices"]}')
        if q.get('optional'):
            flags.append('optional')
        if q.get('unit'):
            flags.append(f'{q["unit"]}, {q.get("min")} to {q.get("max")}')
        if q.get('prefill'):
            flags.append('pre-filled from the student\'s profile')
        if q.get('show_if'):
            flags.append('asked only if measurements are available')
        md.append(f'**{n}. {q["text"]}**  ')
        md.append(f'`{q["id"]}` · {" · ".join(flags)}')
        if q.get('help'):
            md += ['', f'> {q["help"]}']
        opts = q.get('options', [])
        if opts and q['kind'] != 'profile':
            md.append('')
            scored = any('score' in o for o in opts)
            if scored:
                md += ['| Answer | Score |', '|---|---|']
                md += [f'| {o["label"]}{" (" + o["hint"] + ")" if o.get("hint") else ""} | {o.get("score", "")} |' for o in opts]
            else:
                md += [f'- {o["label"]}' for o in opts]
        if q['kind'] == 'profile':
            md += ['', 'Shows age, faculty, academic year and accommodation from the profile, with an option to update them.']
        md.append('')
md += ['## Validated items', '',
       '- **PHQ-2** (questions `e_phq1`, `e_phq2`): Kroenke, Spitzer & Williams (2003), *Medical Care* 41(11):1284-1292. '
       'Wording is unchanged. Each item is scored 0 (not at all) to 3 (nearly every day); a total of 3 or more is a positive screen. '
       'A positive screen is never a diagnosis: the student is shown the counsellor, the 1926 mental health helpline and the anonymous consultation option. '
       'In the domain score the items are reversed so that a higher score stays healthier.',
       '- The diet questions are **indicators**, not a validated composite score. Analyse them item by item.',
       '- Substance-use questions are optional and sensitive; confirm wording, ethics approval and referral procedures with the supervisor and health team before each round.', '']
(ROOT / 'docs' / 'assessment-questionnaire.md').write_text('\n'.join(md), encoding='utf-8')
print(f'{len(domains)} domains, {len(questions)} questions')
