"""Builds the Learn library outputs from one source.

    python -P supabase/seed/build_learn.py

Reads supabase/seed/learn_articles.json and writes:
  - assets/learn/articles.json  (the app's bundled copy, used until the
    database has the articles and when offline)
  - supabase/migrations/20261016120100_learn_library.sql  (database seed)
  - docs/learn-references.md  (every article with its references)
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
articles = json.loads((ROOT / 'supabase' / 'seed' / 'learn_articles.json').read_text(encoding='utf-8'))

# Keep in step with lib/features/library/learn_data.dart and admin/app.js.
TOPICS = {
    'body': 'Body Confidence & Healthy Fitness',
    'womens': "Women's Health & Hormonal Balance",
    'cravings': 'Food Cravings & Eating Habits',
    'heart': 'Heart Health & Disease Prevention',
    'smoking': 'Smoking, Alcohol & Breaking Habits',
    'signs': 'Know the Signs: Health Conditions',
    'skin': 'Skin, Hair & Personal Care',
    'mind': 'Mind, Mood & Emotional Well-being',
    'sleep': 'Sleep, Energy & Recovery',
    'presence': 'Personal Presence & Career Confidence',
    'essentials': 'Everyday Health Essentials',
    'habits': 'Your Habits, Your Health',
    'sexual': 'Sexual Health & STIs',
}

rows = []
for i, a in enumerate(articles):
    assert a['category'] in TOPICS, a['slug']
    assert a['body'].get('references'), a['slug']
    rows.append({
        'slug': a['slug'],
        'title': a['title'],
        'subtitle': a.get('subtitle'),
        'category': a['category'],
        'category_label': TOPICS[a['category']],
        'read_minutes': a.get('read_minutes', 4),
        'author': 'VitalU health team',
        'is_featured': bool(a.get('featured')),
        'is_recommended': False,
        'tags': a.get('tags', []),
        'conditions': a.get('conditions', []),
        'body': a['body'],
        'sort_order': i,
    })

app = ROOT / 'assets' / 'learn' / 'articles.json'
app.write_text(json.dumps(rows, ensure_ascii=False, separators=(',', ':')), encoding='utf-8')


def lit(v):
    if v is None:
        return 'null'
    if isinstance(v, bool):
        return 'true' if v else 'false'
    if isinstance(v, (int, float)):
        return str(v)
    if isinstance(v, dict):
        return "'" + json.dumps(v, ensure_ascii=False).replace("'", "''") + "'::jsonb"
    if isinstance(v, list):
        return "array[" + ', '.join("'" + str(x).replace("'", "''") + "'" for x in v) + "]::text[]" if v else "'{}'::text[]"
    return "'" + str(v).replace("'", "''") + "'"


cols = ['slug', 'title', 'subtitle', 'category', 'category_label', 'read_minutes', 'author', 'is_featured', 'is_recommended', 'tags', 'conditions', 'body', 'sort_order']
values = ',\n'.join('  (' + ', '.join(lit(r[c]) for c in cols) + ')' for r in rows)
sql = f"""-- The Learn library: 13 topics and {len(rows)} evidence-based articles.
-- Generated by supabase/seed/build_learn.py from learn_articles.json.
-- Existing articles are updated in place (bookmarks are kept); admins can
-- hide, edit or add articles afterwards from the dashboard.

insert into public.education_articles ({', '.join(cols)}) values
{values}
on conflict (slug) do update set
  title = excluded.title, subtitle = excluded.subtitle, category = excluded.category,
  category_label = excluded.category_label, read_minutes = excluded.read_minutes, author = excluded.author,
  is_featured = excluded.is_featured, is_recommended = excluded.is_recommended, tags = excluded.tags,
  conditions = excluded.conditions, body = excluded.body, sort_order = excluded.sort_order;
"""
(ROOT / 'supabase' / 'migrations' / '20261016120100_learn_library.sql').write_text(sql, encoding='utf-8')

md = ['# VitalU Learn: articles and references', '',
      f'{len(rows)} articles across {len(TOPICS)} topics. Every article is written for undergraduate students in plain English and '
      'is based on the sources listed under it. Source file: `supabase/seed/learn_articles.json`.', '']
for key, label in TOPICS.items():
    items = [a for a in articles if a['category'] == key]
    md += [f'## {label}', '']
    if key == 'habits':
        md += ['_This topic is also personalised in the app: it recommends articles from the other topics based on the student\'s own water, activity, sleep and meal logs._', '']
    for a in items:
        md += [f'### {a["title"]}', f'_{a.get("subtitle", "")}_ · {a.get("read_minutes", 4)} min read', '']
        for r in a['body']['references']:
            md.append(f'- {r["label"]}' + (f' <{r["url"]}>' if r.get('url') else ''))
        md.append('')
(ROOT / 'docs' / 'learn-references.md').write_text('\n'.join(md), encoding='utf-8')
print(len(rows), 'articles')
